                  <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Bringing Food, Care, and Community Together</div>
                  <div>
                    The Newburgh Enlarged City School District’s commitment to students and families continues beyond the classroom and throughout the year. Under the leadership of Dr. Jackie Manning-Campbell, NECSD is expanding access to food resources through community partnerships and opportunities that respond to the needs of our school community.<br><br>
                    Over the summer, NECSD created Food Bank pop-ups to help families access food during a time when students were away from school and their regular school meals. These distributions brought resources closer to the community and provided another way for families to receive support. Food Bank pop-ups will continue throughout the school year, extending this effort beyond the summer months.<br><br>
                    This work builds on the district’s partnership with the Regional Food Bank of the Hudson Valley and the dedication of community partners and volunteers. As demonstrated through the Backpack Food Program, which provides participating students with nonperishable food every Friday for the weekend, strong partnerships help turn a shared commitment into dependable support. The contributions of Alpha Kappa Alpha, the Kiwanis Club, Regal Bag owner Ted Doering, and other supporters have helped strengthen the district’s ability to meet these needs.<br><br>
                    NECSD also offers food resources within our schools through the food bodega at Newburgh Free Academy’s Main Campus and the food pantry at Meadow Hill. These spaces provide additional points of access, connecting students and families with support within familiar school settings. Together with the pop-ups and Backpack Food Program, they create multiple ways for families to obtain food throughout the year.<br><br>
                    For Dr. Manning-Campbell, addressing food insecurity is part of supporting the whole child. Children’s ability to learn, participate, and thrive is connected to their well-being and access to basic necessities. By strengthening food resources across our school community, NECSD is helping families navigate difficult circumstances with care and dignity.<br><br>
                    These efforts reflect what is possible when schools, community organizations, businesses, and volunteers work together. Whether distributing food at a summer pop-up, stocking a school pantry, or preparing a Friday backpack, each contribution helps make our community a more supportive place for children and families.
                  </div>

                  <hr style="margin:30px 0;border:0;border-top:1px solid #d5dbe0;">

                  <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Third Annual Jumpstart Jamboree: A Strong Start, a Welcoming Community</div>
                  <div>
                    The third annual Jumpstart Jamboree brings families, educators, and more than 30 community partners together to help students prepare for a successful school year. Reflecting Dr. Manning-Campbell’s commitment to family engagement, this welcoming event connects families with resources, introduces them to school experiences, and reminds every child that an entire community is ready to support their growth.<br><br>
                    With games, enrichment activities, and opportunities to connect with district staff and local organizations, the Jamboree combines practical support with the joy of learning and discovery. NIKE provides activities in the gymnasium, giving children opportunities to move, play, and engage with one another. Community partners introduce families to programs and services that can support them throughout the school year, strengthening the connections between home, school, and community.<br><br>
                    For our youngest learners and their families, the Jamboree offers a reassuring introduction to life in NECSD. Families entering prekindergarten and kindergarten meet Buster the Bus and learn about school transportation, helping children become more comfortable with an important part of their new daily routine. Families also learn about school lunches, giving parents and caregivers a better understanding of what their children can expect as they begin school.<br><br>
                    Backpacks help students arrive prepared for the year ahead, while pre-K readiness kits provide resources to support reading, literacy, and learning at home. These materials encourage families to share stories, build early literacy skills, and make learning part of their everyday time together.<br><br>
                    At its heart, Jumpstart Jamboree is about belonging. A welcoming conversation, a new connection, or a child’s excitement about their first backpack can help turn uncertainty into confidence. By bringing resources and relationships together in one joyful space, the third annual Jumpstart Jamboree helps our students and families begin the school year feeling prepared, connected, and welcomed into the Goldback community.
