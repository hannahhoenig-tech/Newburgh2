                  <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Friday Night Lights: Listening to Students, Creating Safe Spaces</div>
                  <div>
                    Following the loss of a student, Superintendent Dr. Manning-Campbell recognized the need to create more opportunities for young people to feel safe, connected, and supported beyond the school day. Her response helped reimagine Friday Night Lights as a space shaped by student voices, caring relationships, and a shared commitment to student safety.<br><br>
                    Dr. Manning-Campbell invited students and community partners—including YAP, SNUG, and local law enforcement—to engage in dialogue about what young people need. These conversations centered on listening: understanding where students feel supported, what opportunities they want, and how the district and community can work together to create welcoming places for them to gather.<br><br>
                    That dialogue helped shape the Friday Night Lights program we have today, providing high school students with a safe space to spend time with friends, explore their interests, and connect with trusted adults. Activities include an open gym, karaoke, cooking classes, a gaming room, and art classes. Dedicated teachers and staff create an environment where students feel welcomed, valued, and encouraged to participate.<br><br>
                    Local police also engage with students through conversations about safety and their experiences in the community. These interactions offer opportunities to build trust, answer questions, and reinforce law enforcement’s role as a partner with the district and its students. Alongside YAP, SNUG, and district staff, their involvement reflects a shared responsibility for supporting young people.<br><br>
                    Friday Night Lights will kick off again on October 30, 2026, with a Halloween event, and the program will continue through August 2027. Students and families are encouraged to check the district website in the upcoming weeks for more information about the kickoff celebration, program dates, and activities.<br><br>
                    Friday Night Lights demonstrates how listening can lead to meaningful action. In responding to loss, Dr. Manning-Campbell brought students and community partners together to strengthen connections and expand access to safe spaces. The program carries a clear message to our high school students: your voices matter, your safety matters, and your community is invested in you.
                  </div>

                  <hr style="margin:30px 0;border:0;border-top:1px solid #d5dbe0;">

                  <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Newburgh Takes the Lead: Coming Together for Healthy Choices</div>
                  <div>
                    This October, the Newburgh Enlarged City School District will proudly host Orange County’s Red Ribbon Week kickoff, bringing students, educators, and community partners together around a shared commitment to substance use prevention and healthy choices. Under the leadership of Dr. Jackie Manning-Campbell, this event marks an exciting step forward in Newburgh’s participation and leadership within the county.<br><br>
                    Red Ribbon Week, observed annually from October 23–31, is a national awareness campaign that encourages communities to educate young people about the dangers of drug use and support healthy decisions. Its origins date back to 1985, when communities began wearing red ribbons to honor Drug Enforcement Administration Agent Enrique “Kiki” Camarena following his murder by drug traffickers. The National Family Partnership organized the first national celebration in 1988, helping turn a community response into a nationwide prevention movement.<br><br>
                    Newburgh had not previously been formally included in Orange County’s coordinated Red Ribbon Week events. Through a renewed partnership with ADAC, Team Newburgh, and other community partners, NECSD is now helping bring this important work directly to our students and community. These relationships have created opportunities for greater participation, shared resources, and a stronger collective focus on prevention.<br><br>
                    On October 23, 2026, NECSD will welcome participants from 10 school districts to the countywide kickoff at our new Newburgh Free Academy Career and Technical Education building. The event will feature a keynote speaker and sessions for visiting middle school students alongside students from Newburgh’s own middle schools. Together, they will have opportunities to learn, connect, and consider how their choices can support their health, goals, and futures.<br><br>
                    Hosting the kickoff in our new CTE building brings two district priorities together: helping students envision meaningful futures and supporting the healthy decisions that allow them to pursue those futures. It also gives NECSD an opportunity to welcome neighboring districts into a space that represents possibility and investment in young people.<br><br>
                    Our students have already begun making their voices heard. During last year’s Red Ribbon contest and event, Newburgh students created artwork addressing drug and alcohol prevention, one student earned first place, two students completed writing projects, and multiple students participated. Their contributions demonstrated the power of student creativity and voice in communicating messages that matter to their peers and community.<br><br>
                    This year’s kickoff builds on that participation and reflects Dr. Manning-Campbell’s commitment to ensuring Newburgh students are represented, supported, and given opportunities to lead. With our schools and community partners working together, NECSD is expanding its place in the county’s prevention efforts and creating more ways for students to contribute.<br><br>
                    In the words of our Superintendent, “There are more of us coming!”
                  </div>

