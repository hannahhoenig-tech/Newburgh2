                <div style="padding-top:10px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Building Futures, Opening Doors!</div>
                <div>
                  The opening of Newburgh Free Academy’s new Career and Technical Education Center marks an exciting investment in our students, our community, and the future of Newburgh. Under the leadership of Dr. Jackie Manning-Campbell, NECSD has brought a long-awaited vision to life: a place where students can discover their talents, explore their interests, and develop practical skills that connect classroom learning to opportunities beyond graduation.<br><br>
                  The new center brings together 17 career pathways: Auto Body, Auto Technology, Barbering, Construction, Cosmetology, Criminal Justice, Culinary Arts, Electrical, Fashion Design, Health Sciences, Heating, Ventilation, and Air Conditioning (HVAC), Pet Grooming, Photography, Plumbing, Veterinary Science, Video Production, and Welding. These offerings give students opportunities to explore careers across the skilled trades, health care, public service, creative industries, and animal care.<br><br>
                  Each pathway creates a different opportunity for students to see their potential. A student interested in building and repairing can explore construction, electrical work, plumbing, HVAC, welding, or automotive careers. Students drawn to creativity can develop their interests through fashion design, photography, video production, barbering, cosmetology, or culinary arts. Those who want to care for others or serve their communities can explore health sciences and criminal justice, while students with a passion for animals can pursue veterinary science and pet grooming.<br><br>
                  Through hands-on learning, students have opportunities to practice problem-solving, teamwork, communication, precision, and responsibility. They can connect what they learn in their academic classes to practical projects, gain confidence in their abilities, and develop a clearer understanding of the education and training their chosen careers require.<br><br>
                  Dr. Manning-Campbell’s commitment to advancing this project reflects a belief that students deserve multiple pathways to success. Whether their next step is college, further technical training, an apprenticeship, employment, or eventually owning a business, the new CTE Center gives them space to imagine that future and begin preparing for it.<br><br>
                  For our students and families, this opening represents possibility. It tells our young people that their interests matter, their talents deserve investment, and their futures are worth building. With its doors now open, the new NFA Career and Technical Education Center begins a new chapter of opportunity, discovery, and Goldback pride.
                </div>

                <hr style="margin:30px 0;border:0;border-top:1px solid #d5dbe0;">

                <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">A Place to Ride, Learn, and Grow</div>
                <div>
                  The Bike Gardens at GAMS and South Middle School are now complete, with Meadow Hill soon to follow, creating welcoming spaces where students can practice bicycle safety, build confidence, and experience the joy of riding. Under the leadership of Dr. Jackie Manning-Campbell, these gardens reflect NECSD’s commitment to healthy habits, outdoor activity, and learning beyond the classroom.<br><br>
                  For Dr. Manning-Campbell, providing safe spaces for students when they are outside our buildings is a priority. Our commitment to children extends beyond the school day and includes creating opportunities for them to remain active, connected, and supported within their community. The Bike Gardens advance that vision by providing dedicated places where students can enjoy riding, develop their skills, and spend time with friends and family.<br><br>
                  These spaces came to life through the generous donation and partnership of the Kiwanis Club. Their investment helped transform a shared vision into places our students can use and enjoy. This contribution demonstrates how community partnerships can expand opportunities for children and strengthen the neighborhoods where they live and learn. We are deeply grateful to Kiwanis for helping make these gardens a reality.<br><br>
                  For a child learning to ride, a safe place to practice can make all the difference. The Bike Gardens provide room to develop balance, steering, stopping, and awareness of others. They also offer opportunities to practice patience, take turns, encourage friends, and celebrate progress. Each successful ride can help a student gain confidence and a greater sense of independence.<br><br>
                  The gardens bring together movement, learning, and the simple joy of being outdoors. They give children a place to try something new, build skills at their own pace, and create positive memories within their community.<br><br>
                  With the gardens complete at GAMS and South Middle School and Meadow Hill soon to follow, more students will benefit from this investment. Together, NECSD and the Kiwanis Club are helping create safe, welcoming spaces where our children can ride, learn, and grow during the school day and beyond.
                </div>

                <hr style="margin:30px 0;border:0;border-top:1px solid #d5dbe0;">

                <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Confidence in the Water, Skills for Life</div>
                <div>
                  Through the Empower Swim Program, the Newburgh Enlarged City School District is helping children develop a lifelong skill while building confidence and learning how to stay safe around water. The program provides free swimming lessons for children ages 4–10 at Newburgh Free Academy’s Main Campus, expanding access to an experience that supports their safety, health, and well-being.<br><br>
                  The program began with a generous donation from United Brain, whose support helped make these lessons possible. NECSD matched the donation, extending the impact of this investment and creating additional opportunities for children to participate. This partnership supports New York State’s guidance encouraging swimming and water safety education for children and families within school communities.<br><br>
                  Under the leadership of Dr. Jackie Manning-Campbell, NECSD continues to prioritize opportunities that support students both inside and outside our school buildings. Swimming is a skill children can carry into adulthood, opening doors to recreation, exercise, and time with family and friends. Providing lessons at no cost helps remove a financial barrier and makes this valuable learning opportunity available to more families.<br><br>
                  More than 70 students received lessons across the program’s first two sessions. Participants had opportunities to become more comfortable in the water, develop swimming skills, and receive guidance on water safety. These experiences help children build confidence while learning the importance of supervision, following safety instructions, and practicing safe behavior around water.<br><br>
                  For a young child, learning to swim can be a meaningful accomplishment. Empower Swim gives participants opportunities to practice, persevere, and celebrate their progress. Each lesson builds a foundation for continued learning and a healthy respect for the water—knowledge that can support children and their families throughout their lives.<br><br>
                  The Empower Swim Program will continue during the 2026–2027 school year, bringing this opportunity to additional children and families across NECSD. Registration links for Sessions 3 and 4 will be shared in the coming weeks. Families are encouraged to watch for upcoming district communications with session details and registration information.<br><br>
                  NECSD extends its sincere appreciation to United Brain for helping launch this program. Through community generosity and the district’s matching investment, Empower Swim is helping our youngest learners gain confidence, develop lasting skills, and become more aware of how to stay safe around water.
                </div>

