                  <div style="padding-top:5px;font-size:20px;font-weight:bold;line-height:24px;color:#212b35">Full Backpacks, Stronger Weekends: A Community Commitment to Our Students</div>
                  <div>
                    For students experiencing food insecurity, the weekend can bring uncertainty about their next meal. Through a partnership with the Regional Food Bank of the Hudson Valley, the Newburgh Enlarged City School District’s Backpack Food Program helps bridge that gap by providing nonperishable food to participating students every Friday. These weekly supplies support children beyond the school day, when access to school meals is unavailable.<br><br>
                    This work depends on a caring network of community partners and volunteers. Our local Alpha Kappa Alpha sorority partners coordinate the volunteers who unload food pallets and pack the weekly supplies for students. Their time, organization, and dedication help turn food deliveries into dependable support for families across our school community.<br><br>
                    When unforeseen circumstances resulted in the loss of the program’s distribution location, finding a new space became essential to continuing this service. Dr. Jackie Manning-Campbell made it her mission to secure a location where volunteers could receive, organize, and pack the food. Having toured the Regional Food Bank’s distribution center, she had seen firsthand the coordination behind this partnership and understood how much families depend on its continued operation.<br><br>
                    With the help and generous contributions of the Kiwanis Club and Regal Bag owner Ted Doering, NECSD secured a new location that is well suited to the program’s distribution needs. Their support provides the space needed to prepare weekly food supplies and make Friday distribution possible across our schools.<br><br>
                    This partnership reflects Dr. Manning-Campbell’s commitment to supporting students both inside and outside our buildings. Helping children access food over the weekend supports their well-being and helps them return to school ready to participate and learn. It also gives families a dependable resource during times of need.<br><br>
                    NECSD extends its heartfelt appreciation to the Regional Food Bank of the Hudson Valley, Alpha Kappa Alpha, the Kiwanis Club, Ted Doering, and every volunteer who contributes to this effort. Together, they are helping ensure that our community’s care for children continues beyond the school week.<br><br>
                    If your family—or a family you know—could benefit from the Backpack Food Program, please contact our McKinney-Vento liaison at <a href="mailto:korogers@necsd.net">korogers@necsd.net</a>. We encourage families to reach out and learn more about this support.
                  </div>

